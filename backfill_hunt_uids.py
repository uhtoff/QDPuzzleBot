#!/usr/bin/env python3
"""Backfill a 6-letter ``uid`` for hunts that don't have one.

Older hunts predate the ``hunts.uid`` short code and were linked by falling back
to the numeric hunt ``id``. The dashboard now resolves hunts by ``uid`` only
(``/hunts/:uid`` → ``SELECT ... FROM hunts WHERE uid = %s``), so a hunt with a
NULL/empty ``uid`` can't be opened. This assigns each such hunt a fresh code.

Codes are generated by the *same* routine new hunts use
(``MySQLHuntJsonDb.generate_uid('uid')``) — 6 uppercase letters, retried until
unique against every existing ``hunts.uid`` — so backfilled codes are
indistinguishable from and won't collide with new ones.

Connection + target database come from the bot's ``config.json`` via
``migrate.connect()`` (same DB the deployed instance uses). Run it on the box
for the instance you want to fix, as that instance's user:

    pipenv run python backfill_hunt_uids.py            # DRY RUN: show what it would do
    pipenv run python backfill_hunt_uids.py --apply    # actually write + commit

Dry run still computes real, unique codes (so you can eyeball them) but rolls the
transaction back and writes nothing.
"""
import sys

import migrate  # repo module: reuses config-driven connect() (autocommit off)
from bot.store.mysqldb import MySQLHuntJsonDb


def main(argv):
    apply = "--apply" in argv[1:]
    unknown = [a for a in argv[1:] if a != "--apply"]
    if unknown:
        print(f"Unknown argument(s): {' '.join(unknown)}")
        print(__doc__)
        return 2

    conn = migrate.connect()
    hunts_db = MySQLHuntJsonDb(conn)
    try:
        cursor = conn.cursor(dictionary=True)
        cursor.execute(
            "SELECT id, name, uid FROM hunts "
            "WHERE uid IS NULL OR uid = '' ORDER BY id"
        )
        missing = cursor.fetchall()
        cursor.close()

        if not missing:
            print("No hunts are missing a uid — nothing to do.")
            return 0

        print(f"{len(missing)} hunt(s) missing a uid:\n")
        for row in missing:
            # generate_uid checks uniqueness against hunts.uid on THIS connection,
            # so it sees uids assigned earlier in this loop (uncommitted but visible
            # to the same transaction) and won't reissue them.
            new_uid = hunts_db.generate_uid("uid")
            update = conn.cursor()
            update.execute(
                "UPDATE hunts SET uid = %s WHERE id = %s", (new_uid, row["id"])
            )
            update.close()
            print(f"  hunt id={row['id']:<6} {new_uid}  ({row['name']!r})")

        if apply:
            conn.commit()
            print(f"\nCommitted {len(missing)} uid(s).")
        else:
            conn.rollback()
            print(
                f"\nDRY RUN — rolled back, no changes written. "
                f"Re-run with --apply to commit these {len(missing)} uid(s)."
            )
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
